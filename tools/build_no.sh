#!/bin/bash
# Номер сборки (он же FM_BUILD, versionCode, CURRENT_PROJECT_VERSION) = время последнего коммита,
# но не больше текущего времени сервера сборки: коммит «из будущего» (часы на компьютере ушли вперёд)
# иначе дал бы огромный номер, и телефоны перестали бы принимать все следующие обновления.
# Если номер уже посчитан в этом запуске (переменная FM_B), берётся он — во всех шагах одно и то же число.
set -eu
if [ -n "${FM_B:-}" ]; then echo "$FM_B"; exit 0; fi
C=$(git log -1 --format=%ct)
N=$(date +%s)
if [ "$C" -gt "$N" ]; then
  echo "::warning::Время коммита ($C) позже текущего ($N) — номер сборки взят по текущему времени" >&2
  echo "$N"
else
  echo "$C"
fi
